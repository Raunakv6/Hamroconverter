import NepaliDate from 'nepali-date-converter';

// Anchor Date: BS 2082-12-25 = AD 2026-04-08
const ANCHOR_BS: BSDate = { year: 2082, month: 12, day: 25 };
const ANCHOR_AD = new Date(2026, 3, 8); // Note: JS months are 0-indexed (April is 3)

// Dynamically correct the calendar data for years 2000-2089 using nepali-date-converter
try {
  for (let y = 2000; y <= 2089; y++) {
    const monthDays: number[] = [];
    for (let m = 0; m < 12; m++) {
      const d = new NepaliDate(y, m, 1);
      let days = 1;
      while (true) {
        d.setDate(days + 1);
        if (d.getMonth() !== m) {
          break;
        }
        days++;
      }
      monthDays.push(days);
    }
    BS_CALENDAR_DATA[y] = monthDays;
  }
} catch (e) {
  console.error("Failed to dynamically populate correct calendar data", e);
}

/**
 * Validates if a BS date is within the supported range and has valid month/day
 */
export function isValidBSDate(date: BSDate): boolean {
  if (date.year < 1970 || date.year > 2100) return false;
  if (date.month < 1 || date.month > 12) return false;
  const daysInMonth = BS_CALENDAR_DATA[date.year][date.month - 1];
  if (date.day < 1 || date.day > daysInMonth) return false;
  return true;
}

/**
 * Calculates total days from BS 1970-01-01 to the given BS date
 */
export function getTotalDaysFromStart(date: BSDate): number {
  let totalDays = 0;
  for (let y = 1970; y < date.year; y++) {
    totalDays += BS_CALENDAR_DATA[y].reduce((a, b) => a + b, 0);
  }
  for (let m = 1; m < date.month; m++) {
    totalDays += BS_CALENDAR_DATA[date.year][m - 1];
  }
  totalDays += (date.day - 1);
  return totalDays;
}

/**
 * Calculates total days from anchor BS date to target BS date
 */
export function getDaysFromAnchorBS(target: BSDate): number {
  const anchorTotalDays = getTotalDaysFromStart(ANCHOR_BS);
  const targetTotalDays = getTotalDaysFromStart(target);
  return targetTotalDays - anchorTotalDays;
}

/**
 * Converts BS Date to AD Date
 */
export function bsToAd(bsDate: BSDate): Date {
  if (!isValidBSDate(bsDate)) {
    throw new Error("Invalid BS Date");
  }
  
  if (bsDate.year >= 2000 && bsDate.year <= 2089) {
    try {
      const nd = new NepaliDate(bsDate.year, bsDate.month - 1, bsDate.day);
      return nd.toJsDate();
    } catch (e) {
      // fallback
    }
  }

  const daysDiff = getDaysFromAnchorBS(bsDate);
  const adDate = new Date(ANCHOR_AD);
  adDate.setDate(adDate.getDate() + daysDiff);
  return adDate;
}

/**
 * Converts AD Date to BS Date
 */
export function adToBs(adDate: Date): BSDate {
  // Let's first check if the date can be converted using nepali-date-converter.
  // This library supports dates within BS 2000 to BS 2089 (which corresponds to AD 1943-04-14 to 2033-04-13).
  const minAD = new Date(1943, 3, 14);
  const maxAD = new Date(2033, 3, 13);
  if (adDate >= minAD && adDate <= maxAD) {
    try {
      const nd = new NepaliDate(adDate);
      const year = nd.getYear();
      if (year >= 2000 && year <= 2089) {
        return {
          year: year,
          month: nd.getMonth() + 1,
          day: nd.getDate()
        };
      }
    } catch (e) {
      // fallback
    }
  }

  const anchorTotalDays = getTotalDaysFromStart(ANCHOR_BS);
  const daysDiff = Math.floor((adDate.getTime() - ANCHOR_AD.getTime()) / (1000 * 60 * 60 * 24));
  let absoluteDays = anchorTotalDays + daysDiff;

  if (absoluteDays < 0) throw new Error("Date out of range (before BS 1970)");

  let currentYear = 1970;
  while (true) {
    const daysInYear = BS_CALENDAR_DATA[currentYear].reduce((a, b) => a + b, 0);
    if (absoluteDays < daysInYear) break;
    absoluteDays -= daysInYear;
    currentYear++;
    if (currentYear > 2100) throw new Error("Date out of range (after BS 2100)");
  }

  let currentMonth = 1;
  while (true) {
    const daysInMonth = BS_CALENDAR_DATA[currentYear][currentMonth - 1];
    if (absoluteDays < daysInMonth) break;
    absoluteDays -= daysInMonth;
    currentMonth++;
  }

  return { year: currentYear, month: currentMonth, day: absoluteDays + 1 };
}
